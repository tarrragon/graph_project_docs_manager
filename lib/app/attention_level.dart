/// 注意力通道的級別（SPEC-003〈注意力通道的到達類別與級別指派表〉）。
///
/// 列舉宣告順序即優先序：`index` 越大級別越高，比較直接用序值，不另立整數
/// 常數（0.1.0-W3-205 語言注意事項：另立常數會使兩份同一事實漂移）。
///
/// 本檔為僅型別、無行為的獨立型別檔——[AppSnackBar] 與未來的仲裁器
/// （`0.1.0-W3-207`）皆 import 本檔，不各自定義（避免 SPEC-003
/// §2.15〈鑑別「綁級別」與「綁呼叫路徑」兩種實作〉警告的兩份同一事實）。
library;

/// 一則提示訊息的注意力級別。
///
/// 三個值與《事件流負載仲裁方法論》〈級別〉表的三個主名一一對應：
/// 可棄／須留痕／不可棄。0.1 無須留痕實例，仍為合法值。
enum AttentionLevel {
  /// 可棄：可被更高或同級別截斷，不留痕跡以外的補救。
  discardable,

  /// 須留痕：截斷時必須留下可稽核的紀錄。
  mustLeaveTrace,

  /// 不可棄：不得被任何級別截斷。
  undroppable,
}
